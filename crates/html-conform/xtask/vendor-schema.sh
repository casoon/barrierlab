#!/usr/bin/env bash
# Vendor the HTML5 RELAX NG schema from validator/validator (vnu) into
# schema/html5/, as-is in RELAX NG compact syntax (.rnc) — no conversion.
#
# Source:  https://github.com/validator/validator
# Commit:  388cb365257d1410d4d32af960dba1cbd1b9af91 (tag 26.8.20)
# License: MIT (schema/html5/LICENSE in the source repo)
#
# Kept in .rnc, unconverted: schema.rs (Phase 05) will be an in-house
# RELAX NG engine (architecturally informed by, but not derived from,
# dholroyd/relaxng-rust — that project is technically strong but was
# unlicensed at the time), reading .rnc natively and handling
# <include>/<div>/`combine` per spec. An earlier version of this script
# ran the schema through Trang + rnginline + a hand-rolled flattener to
# work around limitations in xmloxide's RelaxNG parser (see the upstream
# issues filed against jonwiggins/xmloxide: #52, #53, #54, #55, #56) —
# that whole detour is moot now that xmloxide isn't the RelaxNG engine.
#
# Also vendored, into schema/its2/: its20-html5.rnc and its20-html5-types.rnc
# (schema/its2/ upstream, MIT, (c) 2012 Jirka Kosek; the licence text is in
# each file's own header, there is no LICENSE file in that directory).
# vnu's default schema includes them (`build/build.py`: `include
# "its20-html5.rnc"` and `common.attrs &= its-html-attributes`); src/
# schema_source.rs does the same (barrierlab#188).
#
# Local deviations from upstream are kept as patch files in
# xtask/schema-patches/NNNN-<what>.patch (each starts with a comment saying
# what, why and which file). They are applied in name order after the
# download; a patch that does not apply aborts the script before anything in
# schema/html5/ is touched. Paths in the patches are relative to the module
# directory (`patch -p1`).
#
# Requires: curl, patch, diff.
#
# Usage: xtask/vendor-schema.sh           vendor + patch into schema/html5/
#        xtask/vendor-schema.sh --check   vendor + patch into a temp dir and
#                                         diff against the committed tree;
#                                         exit 1 on any difference. Needs
#                                         network, so it is not run in CI.

set -euo pipefail

VNU_COMMIT="388cb365257d1410d4d32af960dba1cbd1b9af91"
RAW_BASE="https://raw.githubusercontent.com/validator/validator/${VNU_COMMIT}/schema/html5"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
DEST_DIR="${REPO_ROOT}/schema/html5"
ITS_DEST_DIR="${REPO_ROOT}/schema/its2"
ITS_RAW_BASE="https://raw.githubusercontent.com/validator/validator/${VNU_COMMIT}/schema/its2"
PATCH_DIR="${SCRIPT_DIR}/schema-patches"

MODE="write"
case "${1:-}" in
  "") ;;
  --check) MODE="check" ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

for tool in curl patch diff; do
  if ! command -v "${tool}" >/dev/null 2>&1; then
    echo "error: ${tool} not found on PATH" >&2
    exit 1
  fi
done

# RELAX NG compact-syntax modules that make up the vnu HTML5 schema.
# html5.rnc is the entry point; the others are pulled in via `include`.
# rdfa.rnc is not reachable from html5.rnc either: vnu's build assembles it
# into the default schema (`.drivers/html5-all.rnc` -> `html5full-rdfa.rnc`,
# generated by build/build.py as html5full.rnc + `include "rdfa.rnc"`), so
# src/schema_source.rs includes it from its own entry point (barrierlab#173).
# (xhtml5.rnc, html5exclusions.rnc, web-forms-scripting.rnc and
# web-forms2-scripting.rnc exist in the source directory but are not
# reachable from html5.rnc's include graph -- they belong to the XHTML5 /
# scripting-profile variants this crate does not target yet.)
MODULES=(
  applications.rnc
  aria.rnc
  block.rnc
  common.rnc
  core-scripting.rnc
  data.rnc
  embed.rnc
  form-datatypes.rnc
  html5.rnc
  media.rnc
  meta.rnc
  microdata.rnc
  phrase.rnc
  rdfa.rnc
  revision.rnc
  ruby.rnc
  sectional.rnc
  structural.rnc
  tables.rnc
  web-components.rnc
  web-forms.rnc
  web-forms2.rnc
)

ITS_MODULES=(
  its20-html5.rnc
  its20-html5-types.rnc
)

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "${WORK_DIR}"' EXIT

echo "==> downloading ${#MODULES[@]} .rnc modules from validator/validator@${VNU_COMMIT}"
for module in "${MODULES[@]}"; do
  curl -sSf -o "${WORK_DIR}/${module}.raw" "${RAW_BASE}/${module}"
  # REUSE-IgnoreStart
  { printf '# SPDX-License-Identifier: MIT\n'; cat "${WORK_DIR}/${module}.raw"; } > "${WORK_DIR}/${module}"
  # REUSE-IgnoreEnd
  rm "${WORK_DIR}/${module}.raw"
done
curl -sSf -o "${WORK_DIR}/LICENSE" "${RAW_BASE}/LICENSE"

mkdir -p "${WORK_DIR}/its2"
for module in "${ITS_MODULES[@]}"; do
  curl -sSf -o "${WORK_DIR}/its2/${module}.raw" "${ITS_RAW_BASE}/${module}"
  # REUSE-IgnoreStart
  { printf '# SPDX-License-Identifier: MIT\n'; cat "${WORK_DIR}/its2/${module}.raw"; } > "${WORK_DIR}/its2/${module}"
  # REUSE-IgnoreEnd
  rm "${WORK_DIR}/its2/${module}.raw"
done

if [ ! -d "${PATCH_DIR}" ]; then
  echo "error: ${PATCH_DIR} missing" >&2
  exit 1
fi
PATCH_COUNT=0
for patch_file in "${PATCH_DIR}"/*.patch; do
  echo "==> applying $(basename "${patch_file}")"
  if ! patch -s -p1 -F0 -d "${WORK_DIR}" < "${patch_file}"; then
    echo "error: $(basename "${patch_file}") does not apply to ${VNU_COMMIT}" >&2
    exit 1
  fi
  PATCH_COUNT=$((PATCH_COUNT + 1))
done

if [ "${MODE}" = "check" ]; then
  status=0
  for module in "${MODULES[@]}" LICENSE; do
    if ! diff -u "${DEST_DIR}/${module}" "${WORK_DIR}/${module}"; then
      status=1
    fi
  done
  for module in "${ITS_MODULES[@]}"; do
    if ! diff -u "${ITS_DEST_DIR}/${module}" "${WORK_DIR}/its2/${module}"; then
      status=1
    fi
  done
  for committed in "${ITS_DEST_DIR}"/*.rnc; do
    if [ ! -f "${WORK_DIR}/its2/$(basename "${committed}")" ]; then
      echo "only in committed tree: its2/$(basename "${committed}")" >&2
      status=1
    fi
  done
  # A committed module the script no longer produces would be a stale leftover.
  for committed in "${DEST_DIR}"/*.rnc; do
    if [ ! -f "${WORK_DIR}/$(basename "${committed}")" ]; then
      echo "only in committed tree: $(basename "${committed}")" >&2
      status=1
    fi
  done
  if [ "${status}" -ne 0 ]; then
    echo "error: committed schema/html5 differs from upstream + patches" >&2
    exit 1
  fi
  echo "==> ok: schema/html5 equals ${VNU_COMMIT} + ${PATCH_COUNT} patch(es)"
  exit 0
fi

mkdir -p "${DEST_DIR}"
rm -f "${DEST_DIR}"/*.rnc
for module in "${MODULES[@]}" LICENSE; do
  cp "${WORK_DIR}/${module}" "${DEST_DIR}/${module}"
done
mkdir -p "${ITS_DEST_DIR}"
rm -f "${ITS_DEST_DIR}"/*.rnc
for module in "${ITS_MODULES[@]}"; do
  cp "${WORK_DIR}/its2/${module}" "${ITS_DEST_DIR}/${module}"
done

echo "==> done: ${#MODULES[@]} .rnc modules in ${DEST_DIR}, ${#ITS_MODULES[@]} in ${ITS_DEST_DIR}"
